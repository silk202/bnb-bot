/**
 * Full-source archive, generated by `bun run source:package` into
 * public/downloads/ and therefore served from the app's own origin. Kept as
 * one path in one place so the menu, the downloads page and the packaging
 * script cannot drift apart.
 */
const SOURCE_ARCHIVE_URL = "/downloads/flashbolt-source.zip";
/**
 * Name the file lands under in the operator's own Downloads folder. Set
 * explicitly so the saved file is self-describing and versioned instead of
 * inheriting whatever the browser derives from the URL.
 */
const SOURCE_ARCHIVE_FILENAME = `flashbolt-v${__APP_VERSION__}-source.zip`;

/** Detect which terminal the user is currently on from the URL. */
function flavorFromPath(pathname: string): TerminalFlavor {
  if (pathname.startsWith("/sol-terminal")) return "sol";
  if (pathname.startsWith("/trade-terminal")) return "trade";
  return "bnb";
}

/**
 * True on phones/tablets — there the t.me link is an Android App Link /
 * iOS Universal Link, so it opens the TAEngine bot straight in the Telegram
 * APP (and degrades to Telegram's own get-app/open-in-web page when the app
 * isn't installed). iPadOS 13+ masquerades as desktop Safari, so touch
 * Macintoshes count as mobile too.
 */
function prefersMobileTelegram(): boolean {
  if (typeof navigator === "undefined") return false;
  const ua = navigator.userAgent;
  if (/Android|iPhone|iPad|iPod|Windows Phone|IEMobile|Opera Mini/i.test(ua)) {
    return true;
  }
  return (
    /Macintosh/.test(ua) &&
    typeof navigator.maxTouchPoints === "number" &&
    navigator.maxTouchPoints > 1
  );
}

/**
 * Platform-aware deep link for the TAEngine bot — delegated to the shared
 * builder so the native-anchor href and the connect-then-redirect path
 * always navigate to the exact same place:
 *   • mobile/tablet → `https://t.me/<bot>?start=<code>` — the official
 *     universal link: the Telegram app opens the bot chat directly
 *     (Telegram's own fallback page only if the app is missing);
 *   • desktop → `https://web.telegram.org/k/#?tgaddr=<encoded t.me link>`
 *     (with a pairing code) or `#@<bot>` (without) — Web K resolves both
 *     straight to the bot chat, no t.me interstitial in between.
 * The builder's doc comment pins the verified Web K router behaviour,
 * including why `#@<bot>?start=<code>` is NOT used (Web K silently drops
 * the payload on that branch). On a plain /start the server-side auto-pair
 * policy (default ON) links the chat and boots the console regardless.
 */
function telegramBotLink(username: string, code: string | null): string {
  return buildTelegramBotLink({
    username,
    code,
    mobile: prefersMobileTelegram(),
  });
}

/**
 * Account menu — the avatar at the top right of the terminal, shown after
 * the world clock + date. It displays the registered email address, the
 * terminal switcher (BNB FlashBolt ⇄ SOL FlashBolt) and a Support entry
 * that opens the free support chatbot.
 */
export function AccountMenu() {
  const { user, signOut } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();
  const [supportOpen, setSupportOpen] = useState(false);
  const [botBusy, setBotBusy] = useState(false);
  const [menuOpen, setMenuOpen] = useState(false);
  // Real auto-connect — webhook self-heal + live pairing code + bot identity
  // (the same server action the dialog uses, run here so the account menu can
  // open Web Telegram directly with no extra button presses).
  const autoConnectBot = useAction(api.telegramBot.autoConnectBot);
  // Live Telegram bot health for the menu row (real webhook self-heal
  // verdict + paired-chat count, stamped by the 10-minute self-heal cron and
  // every dialog auto-connect). Non-throwing query; renders nothing when the
  // server does not recognize the session as operator.
  const botHealth = useQuery(
    api.telegramBot.getBotHealth,
    { deviceToken: getDeviceToken() ?? undefined },
  ) as
    | {
        recognized: boolean;
        tokenConfigured?: boolean;
        webhookOk?: boolean | null;
        linkedChats?: number;
        /** Cached @username — enables the instant direct-to-Web-Telegram open. */
        botUsername?: string | null;
        /** Live pairing code carried in the deep link (null when expired). */
        pairing?: { code: string; expiresAt: number } | null;
      }
    | undefined;
  const showBotHealth =
    botHealth?.recognized === true &&
    (botHealth.tokenConfigured === false || typeof botHealth.webhookOk === "boolean");
  const email = user?.email ?? "";
  const initial = (email || "T").slice(0, 1).toUpperCase();

  const current = flavorFromPath(location.pathname);
  // Switcher rules: BNB ⇄ SOL offer each other; FlashBolt Trade offers BOTH.
  // "Switch to FlashBolt Trade" is additionally offered on BNB and SOL —
  // but ONLY for operator sessions (operator sign-in or continue-as-guest).
  // Subscribers never see it (FlashBolt Trade is operator-only by design).
  const isOperatorSession = getGrant()?.role !== "subscriber";
  const others: TerminalFlavor[] =
    current === "bnb"
      ? isOperatorSession
        ? ["sol", "trade"]
        : ["sol"]
      : current === "sol"
        ? isOperatorSession
          ? ["bnb", "trade"]
          : ["bnb"]
        : ["bnb", "sol"];

  const handleSwitchTerminal = (target: TerminalFlavor) => {
    setStoredFlavor(target);
    navigate(FLAVOR_META[target].path);
  };

  const handleSignOut = async () => {
    try {
      await signOut();
    } finally {
      navigate("/");
    }
  };

  /**
   * Shared connect — ONE in-flight auto-connect per session, reused by both
   * pre-warmers and the click path. The resolved bot identity is cached in a
   * ref, so a click never repeats the server round-trip and never stacks a
   * second action on top of an in-flight one (duplicate getMe/webhook calls
   * are exactly what made the first open feel slow).
   */
  const identityRef = useRef<{ username: string | null; code: string | null } | null>(null);
  const connectPromiseRef = useRef<Promise<{
    username: string | null;
    code: string | null;
  } | null> | null>(null);
  const runConnect = useCallback(() => {
    if (connectPromiseRef.current) return connectPromiseRef.current;
    const p = autoConnectBot({ deviceToken: getDeviceToken() ?? undefined })
      .then((res) => {
        if (res.deviceToken) setDeviceToken(res.deviceToken);
        identityRef.current = {
          username: res.botUsername ?? null,
          code: res.pairing?.code ?? null,
        };
        return identityRef.current;
      })
      .catch(() => {
        connectPromiseRef.current = null; // allow an honest retry later
        return null;
      });
    connectPromiseRef.current = p;
    return p;
  }, [autoConnectBot]);

  /**
   * PRE-WARM #1 — the moment the menu opens. If the health query has not
   * produced a cached @username yet, fire the shared connect immediately so
   * the click never waits on it. When health already carries the identity,
   * the row is already a native anchor — nothing to warm.
   */
  const prewarmedRef = useRef(false);
  useEffect(() => {
    if (!menuOpen || prewarmedRef.current) return;
    if (botHealth === undefined) return; // wait for the reactive verdict
    prewarmedRef.current = true;
    if (botHealth.recognized !== true || botHealth.botUsername) return;
    void runConnect();
  }, [menuOpen, botHealth, runConnect]);

  /**
   * PRE-WARM #2 — shortly after mount, independent of the menu. On a cold
   * session this resolves the bot identity BEFORE the user even opens the
   * menu, so the very first click already takes the instant native-anchor
   * path. Skipped once health shows a cached username; never fired for
   * subscriber sessions (the row is operator-only).
   */
  useEffect(() => {
    if (prewarmedRef.current) return;
    if (botHealth?.recognized === true && botHealth.botUsername) {
      prewarmedRef.current = true;
      return;
    }
    if (getGrant()?.role === "subscriber") {
      prewarmedRef.current = true;
      return;
    }
    const t = setTimeout(() => {
      if (prewarmedRef.current) return;
      prewarmedRef.current = true;
      void runConnect();
    }, 2500);
    return () => clearTimeout(t);
  }, [botHealth, runConnect]);

  /**
   * COMPLETE AUTO-OPEN — a real same-tab redirect to Telegram (NO popup
   * window, no window.open, no dialog). Reuses the shared connect promise:
   * if a pre-warmer already resolved the identity this is instantaneous;
   * otherwise exactly ONE server round-trip happens, then the tab navigates.
   * On mobile the t.me URL hands the navigation straight to the Telegram
   * app; on desktop the tab becomes Web Telegram on the bot chat.
   */
  const connectAndRedirect = async () => {
    if (botBusy) return; // one in-flight connect at a time
    setBotBusy(true);
    try {
      let identity = await runConnect();
      if (!identity?.username && botHealth?.recognized && botHealth.botUsername) {
        identity = {
          username: botHealth.botUsername,
          code:
            botHealth.pairing && botHealth.pairing.expiresAt > Date.now()
              ? botHealth.pairing.code
              : null,
        };
      }
      // The username below is only resolvable server-side (getMe + a cached
      // config row). A FIRST connect can land here when the token is missing
      // from the deployment's Keys or the getMe call is still transient —
      // retrying leaves the row spinner up and lets the /10 self-heal cron
      // (or a dialog auto-connect) stamp a username. Never construct or throw
      // the token-missing toast on this path: that message assumes a token
      // absence, not a just-failed first connect.
      const username =
        identity?.username ?? identityRef.current?.username ?? null;
      const code = identity?.code ?? identityRef.current?.code ?? null;
      if (username) {
        window.location.assign(telegramBotLink(username, code));
        return; // navigating away
      }
      if (botHealth?.recognized && botHealth.botUsername) {
        // Sticky cache: pre-warm stamped it, but the click-resolved connect
        // came back empty (rare transient). Fall back to the cache instead of
        // treating this as a hard failure.
        const ev = new Event("click", { bubbles: true, cancelable: true });
        const anchor = document.querySelector<HTMLAnchorElement>(
          'a[href^="https://t.me/"]',
        );
        if (anchor) {
          anchor.dispatchEvent(ev);
          return;
        }
        window.location.assign(
          telegramBotLink(botHealth.botUsername, null),
        );
        return;
      }
      // One honest fallback for the row: a retry is a single tap away, so the
      // menu closes quietly (spinner stays available) and no toast assumes a
      // token is missing.
      setMenuOpen(false);
      toast.error(
        "TAEngine is connecting — this can take a moment. Reconnect in Settings when ready.",
      );
    } catch (err) {
      // Honest, quiet fallback: a toast — never a popup window, never a modal.
      setMenuOpen(false);
      toast.error(err instanceof Error ? err.message : "Could not open Telegram — try again.");
    } finally {
      setBotBusy(false);
    }
  };

  // When the bot identity is already cached server-side, the menu item is a
  // REAL anchor whose href is the Telegram deep link — clicking it navigates
  // the tab natively (zero popups, zero JS). Otherwise the click runs the
  // one-time connect above and then redirects the same tab.
  const botMenuReady = botHealth?.recognized === true && !!botHealth.botUsername;
  const freshBotLink = () =>
    botHealth!.botUsername
      ? telegramBotLink(
          botHealth!.botUsername,
          botHealth!.pairing && botHealth!.pairing.expiresAt > Date.now()
            ? botHealth!.pairing.code
            : null,
        )
      : null;
  const botMenuHref = botMenuReady ? freshBotLink() : null;

  return (
    <>
      <DropdownMenu open={menuOpen} onOpenChange={setMenuOpen}>
        <DropdownMenuTrigger asChild>
          <button
            type="button"
            aria-label="Account menu"
            className="inline-flex size-9 items-center justify-center rounded-full border border-border/70 bg-primary/15 text-primary transition-colors hover:bg-primary/25"
          >
            <span className="text-sm font-bold">{initial}</span>
          </button>
        </DropdownMenuTrigger>
        <DropdownMenuContent align="end" className="w-72">
          <DropdownMenuLabel className="flex flex-col gap-1">
            <span className="text-[11px] font-semibold uppercase tracking-wider text-muted-foreground">
              Account
            </span>
            <span className="flex items-center gap-2 text-sm font-medium text-foreground">
              <Mail className="size-4 shrink-0 text-muted-foreground" />
              <span className="truncate">
                {email || "Guest account — no email set"}
              </span>
            </span>
          </DropdownMenuLabel>
          <DropdownMenuSeparator />
          {/* Terminal switcher — BNB FlashBolt ⇄ SOL FlashBolt, available on
              both terminals (current one marked). */}
          {others.map((target) => {
            const Icon = FLAVOR_META[target].icon;
            const from =
              current === "bnb" ? "BNB" : current === "sol" ? "SOL" : "Trade";
            const to =
              target === "bnb" ? "BNB" : target === "sol" ? "SOL" : "Trade";
            return (
              <DropdownMenuItem key={target} onSelect={() => handleSwitchTerminal(target)}>
                <Icon className="size-4" />
                Switch to {FLAVOR_META[target].title}
                <span className="ml-auto text-[10px] font-semibold text-muted-foreground">
                  {from} → {to}
                </span>
              </DropdownMenuItem>
            );
          })}
          {getGrant()?.role !== "subscriber" && (
            <>
              {botMenuHref ? (
                // READY — complete auto-open: the row IS the Telegram deep
                // link. A native anchor click navigates the tab (mobile → the
                // Telegram app, desktop → Web Telegram on the bot chat). No
                // window.open, no popup, no intermediate page; the menu closes
                // natively like any link.
                <DropdownMenuItem asChild>
                  <a href={botMenuHref} rel="noreferrer">
                    <Bot className="size-4" />
                    <span className="truncate">Telegram Bot</span>
                    <span className="ml-auto flex shrink-0 items-center gap-1.5 text-[10px] font-semibold text-primary">
                      {showBotHealth && (
                        <>
                          {botHealth!.linkedChats ? (
                            <span className="text-muted-foreground">
                              {botHealth!.linkedChats} chat{botHealth!.linkedChats === 1 ? "" : "s"}
                            </span>
                          ) : null}
                          {botHealth!.tokenConfigured === false ? (
                            <CircleAlert className="size-3.5 text-amber-500" aria-label="Bot token not configured" />
                          ) : botHealth!.webhookOk === true ? (
                            <Check className="size-3.5 text-emerald-500" aria-label="Webhook live" />
                          ) : botHealth!.webhookOk === false ? (
                            <CircleAlert className="size-3.5 text-amber-500" aria-label="Webhook offline — opening heals it" />
                          ) : null}
                        </>
                      )}
                      Open in Telegram
                    </span>
                  </a>
                </DropdownMenuItem>
              ) : (
                // FIRST CONNECT — resolve the bot identity once (row spinner),
                // then REDIRECT the tab to Telegram. Honest, quiet failure via
                // a toast — never a popup window, never a modal.
                <DropdownMenuItem
                  onSelect={(e) => {
                    e.preventDefault(); // keep the menu open on the spinner row
                    void connectAndRedirect();
                  }}
                >
                  <Bot className="size-4" />
                  <span className="truncate">Telegram Bot</span>
                  <span className="ml-auto flex shrink-0 items-center gap-1.5 text-[10px] font-semibold text-primary">
                    {showBotHealth && (
                      <>
                        {botHealth!.linkedChats ? (
                          <span className="text-muted-foreground">
                            {botHealth!.linkedChats} chat{botHealth!.linkedChats === 1 ? "" : "s"}
                          </span>
                        ) : null}
                        {botHealth!.tokenConfigured === false ? (
                          <CircleAlert className="size-3.5 text-amber-500" aria-label="Bot token not configured" />
                        ) : botHealth!.webhookOk === true ? (
                          <Check className="size-3.5 text-emerald-500" aria-label="Webhook live" />
                        ) : botHealth!.webhookOk === false ? (
                          <CircleAlert className="size-3.5 text-amber-500" aria-label="Webhook offline — opening heals it" />
                        ) : null}
                      </>
                    )}
                    {botBusy ? (
                      <span className="inline-flex items-center gap-1">
                        <Loader2 className="size-3.5 animate-spin" aria-label="Opening Telegram" />
                        Opening…
                      </span>
                    ) : (
                      "Open in Telegram"
                    )}
                  </span>
                </DropdownMenuItem>
              )}
              <DropdownMenuItem onSelect={() => navigate("/download")}>
                <Code className="size-4" />
                Source Code
                <span className="ml-auto text-[10px] font-semibold text-muted-foreground">
                  Download
                </span>
              </DropdownMenuItem>
              {/* Direct source download — operator/guest only (this whole block
                  is skipped for subscribers). A native anchor, so the click
                  starts the transfer with no page, GitHub archive endpoint or
                  release page in the path. The zip is built by
                  scripts/package-source.sh into public/downloads/, i.e. it
                  ships inside the app's own dist/ bundle. */}
              <DropdownMenuItem asChild>
                <a href={SOURCE_ARCHIVE_URL} download={SOURCE_ARCHIVE_FILENAME}>
                  <Download className="size-4" />
                  Download source
                  <span className="ml-auto text-[10px] font-semibold text-muted-foreground">
                    Full app · ZIP
                  </span>
                </a>
              </DropdownMenuItem>
            </>
          )}
          <DropdownMenuItem onSelect={() => setSupportOpen(true)}>
            <LifeBuoy className="size-4" />
            Support
            <span className="ml-auto text-[10px] font-semibold text-primary">
              AI assistant
            </span>
          </DropdownMenuItem>
          <DropdownMenuSeparator />
          <DropdownMenuItem variant="destructive" onSelect={() => void handleSignOut()}>
            <LogOut className="size-4" />
            Sign out
          </DropdownMenuItem>
        </DropdownMenuContent>
      </DropdownMenu>
      <SupportChat open={supportOpen} onOpenChange={setSupportOpen} />
    </>
  );
}
